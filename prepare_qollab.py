"""Generate a paste-ready Qollab file without changing the reference modules."""

import ast
import argparse
from html.parser import HTMLParser
import json
import hashlib
from pathlib import Path

from qphylo_core import validate_weights
from qphylo_run_steps import checkpoint_from_report

ROOT = Path(__file__).resolve().parent


def without_local_imports_and_cli(path):
    source = path.read_text()
    lines = source.splitlines(keepends=True)
    remove = set()
    for node in ast.parse(source).body:
        local_import = isinstance(node, ast.ImportFrom) and node.module in (
            "qphylo_core", "qphylo_qaoa", "qphylo_run_steps", "qphylo_benchmark")
        cli_guard = isinstance(node, ast.If) and isinstance(node.test, ast.Compare) and (
            isinstance(node.test.left, ast.Name) and node.test.left.id == "__name__")
        if local_import or cli_guard:
            remove.update(range(node.lineno - 1, node.end_lineno))
    return "".join(line for i, line in enumerate(lines) if i not in remove)


def checkpoint_from_file(path):
    class Messages(HTMLParser):
        def __init__(self):
            super().__init__()
            self.parts = []

        def handle_data(self, data):
            self.parts.append(data)

    source = Path(path).read_text()
    if Path(path).suffix.lower() == ".json":
        value = json.loads(source)
        return value if "contract" in value else checkpoint_from_report(value)
    if Path(path).suffix.lower() == ".html":
        parser = Messages()
        parser.feed(source)
        source = "\n".join(parser.parts)
    lines = source.splitlines()
    for prefix in ("RESUME_STATE_JSON:", "REPORT_JSON:"):
        matches = [line.split(prefix, 1)[1].strip() for line in lines if prefix in line]
        if matches:
            value = json.loads(matches[-1])
            return value if prefix == "RESUME_STATE_JSON:" else checkpoint_from_report(value)
    raise ValueError("No optimizer checkpoint/report was found in this output.")


PRESETS = {
    "eight_smoke": ("seeded_coordinate_search", 9),
    "eight_coordinate": ("seeded_coordinate_search", 31),
    "eight_cobyla": ("COBYLA", 31),
}


def protein_graph(path):
    """Validate a preprocessing export and freeze its provenance for Qollab."""
    path = Path(path).resolve()
    graph = json.loads(path.read_text())
    if graph.get("schema") != "qphylo-protein-graph-v1":
        raise ValueError("Expected a qphylo protein graph export.")
    weights = validate_weights(graph["weights"])
    labels = graph["labels"]
    if (len(labels) != len(weights) or any(not isinstance(v, str) or not v for v in labels)
            or len(set(labels)) != len(labels)):
        raise ValueError("Graph labels must be unique nonempty strings, one per vertex.")
    if not 3 <= len(labels) <= 12:
        raise ValueError("This exact-diagnostic pilot supports 3–12 taxa.")
    manifest = json.loads((path.parent / "manifest.json").read_text())
    if (manifest.get("status") != "graph_ready" or
            not manifest.get("diagnostics", {}).get("connected")):
        raise ValueError("Protein graph requires review; do not submit it yet.")
    if manifest["labels"] != labels or manifest["n_taxa"] != len(labels):
        raise ValueError("Graph and manifest taxa disagree.")
    for key in ("source_sha256", "blast_hits_sha256"):
        if graph["provenance"][key] != manifest[key]:
            raise ValueError(f"Graph and manifest {key} disagree.")
    # Verify the frozen graph also agrees with the local audited matrix.
    import csv
    with (path.parent / "affinity_matrix.csv").open(newline="") as stream:
        rows = list(csv.reader(stream))
    if (rows[0][1:] != labels or [r[0] for r in rows[1:]] != labels or
            validate_weights([[float(v) for v in r[1:]] for r in rows[1:]]) != weights):
        raise ValueError("Graph disagrees with the audited affinity matrix.")
    provenance = {"kind": "protein_derived", "graph_sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                  "preprocessing": manifest}
    return [list(row) for row in weights], labels, provenance


def build(resume_path=None, preset=None, seed=42, output_path=None, graph_path=None):
    if sum(bool(v) for v in (preset, resume_path, graph_path)) > 1:
        raise ValueError("Choose a preset, checkpoint, or protein graph, only one.")
    if preset and preset not in PRESETS:
        raise ValueError("Unknown preset.")
    parts = ["# GENERATED by prepare_qollab.py. Edit the source modules, then rebuild.\n"
             "# Paste this whole file into Qollab's main Python file.\n"
             "# Qollab supplies backend; no main() wrapper is used.\n\n"]
    if preset:
        parts.append(f"# PRESET: {preset}; initialization seed: {seed}.\n")
    graph = protein_graph(graph_path) if graph_path else None
    if graph:
        parts.append("# PROTEIN GRAPH: embedded weights and provenance; no supporting uploads needed.\n"
                     "# Select Built-in simulator (24q); COBYLA requires multiple jobs.\n")
    checkpoint = checkpoint_from_file(resume_path) if resume_path else None
    if checkpoint and checkpoint.get("status") == "failed":
        raise ValueError("Checkpoint records a failed run. Inspect its error/job before proceeding.")
    for relative in ("qphylo_core.py", "qphylo_qaoa.py", "qphylo_run_steps.py", "qphylo_benchmark.py",
                     "qollab_smoke/cut_pilot.py"):
        parts.append(f"\n# ---- Source: {relative} ----\n")
        source = without_local_imports_and_cli(ROOT / relative)
        if (checkpoint or preset or graph) and relative == "qollab_smoke/cut_pilot.py":
            # Replace only run configuration assignments, with Python literals.
            replacements = {"resume_json": json.dumps(checkpoint),
                            "execution_mode": "one_job",
                            "fixture": "restored_checkpoint",
                            **{key: checkpoint["contract"][key] for key in (
                                "mode", "backend_label", "weights", "labels", "target_size")}} if checkpoint else {
                                    "mode": "toy_tree", "execution_mode": "multi_job",
                                    "backend_label": "Built-in simulator (ideal)",
                                    "fixture": "hierarchical8", "seed": seed,
                                    "optimizer": PRESETS[preset][0] if preset else "COBYLA",
                                    "evaluation_budget": PRESETS[preset][1] if preset else 31,
                                    "simulator_seed": 20261010 + seed}
            if graph:
                replacements.update(mode="protein_tree", fixture="protein1822" if
                    Path(graph_path).parent.name == "protein1822" else "protein_graph",
                    weights=graph[0], labels=graph[1], dataset_provenance=graph[2])
            lines = source.splitlines(keepends=True)
            for node in reversed(ast.parse(source).body):
                if isinstance(node, ast.Assign) and len(node.targets) == 1:
                    target = node.targets[0]
                    if (checkpoint or graph) and isinstance(target, ast.Tuple) and [v.id for v in target.elts] == ["weights", "labels"]:
                        lines[node.lineno - 1:node.end_lineno] = [
                            f"weights = {replacements['weights']!r}\nlabels = {replacements['labels']!r}\n"]
                    elif (preset or graph) and isinstance(target, ast.Name) and target.id == "simulator_seed":
                        lines[node.lineno - 1:node.end_lineno] = ["simulator_seed = 20261010 + seed\n"]
                    elif isinstance(target, ast.Name) and target.id in replacements:
                        lines[node.lineno - 1:node.end_lineno] = [
                            f"{target.id} = {replacements[target.id]!r}\n"]
                    elif checkpoint and isinstance(target, ast.Name) and target.id == "config":
                        lines[node.lineno - 1:node.end_lineno] = [
                            f"config = QAOAConfig(**{checkpoint['contract']['config']!r})\n"]
            source = "".join(lines)
        parts.append(source)
    output = "".join(parts)
    ast.parse(output)
    filename = f"{preset}.py" if preset else "protein_qaoa_standalone.py" if graph else "qaoa_cut_standalone.py"
    target = ROOT / output_path if output_path else ROOT / "qollab_smoke" / filename
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(output)
    return target


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--resume", help="Saved Qollab output HTML, text or checkpoint JSON")
    parser.add_argument("--preset", choices=PRESETS, help="Eight-taxon smoke or matched optimizer comparison")
    parser.add_argument("--seed", type=int, default=42, help="Initialization seed for a preset")
    parser.add_argument("--graph", help="Audited protein graph.json; embeds weights and provenance (COBYLA, budget 31)")
    parser.add_argument("--output", help="Optional destination, for separate files with each preset seed")
    args = parser.parse_args()
    print(build(args.resume, args.preset, args.seed, args.output, args.graph))
